  const norm = s => s.replace(/\s+/g, " ").trim();
  let lang = "ar";
  try { lang = localStorage.getItem("lang") || ""; } catch (e) {}
  if (lang !== "ar" && lang !== "en") lang = (navigator.language || "").toLowerCase().startsWith("ar") ? "ar" : "en";
  const orig = new WeakMap();           // عقدة نصية -> النص العربي الأصلي
  const ATTRS = ["alt", "aria-label", "title", "content", "placeholder"];

  const t = ar => (lang === "en" && EN[norm(ar)]) || ar;

  function tr(text) { // يحافظ على المسافات في الأطراف
    const k = norm(text);
    const v = EN[k];
    if (!v) return null;
    return text.match(/^\s*/)[0] + v + text.match(/\s*$/)[0];
  }

  function apply(root) {
    root = root || document.documentElement;
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: n => /^(SCRIPT|STYLE|NOSCRIPT)$/.test(n.parentNode.nodeName) || !n.nodeValue.trim() ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT
    });
    for (let n; (n = w.nextNode());) {
      if (!orig.has(n)) { if (!/[؀-ۿ]/.test(n.nodeValue)) continue; orig.set(n, n.nodeValue); }
      const o = orig.get(n);
      const v = lang === "en" ? tr(o) : null;
      const next = v === null ? o : v;
      if (n.nodeValue !== next) n.nodeValue = next;
    }
    const els = root.querySelectorAll ? [root, ...root.querySelectorAll("*")] : [];
    els.forEach(el => {
      ATTRS.forEach(a => {
        if (!el.hasAttribute || !el.hasAttribute(a)) return;
        const key = "data-ar-" + a;
        if (!el.hasAttribute(key)) {
          const val = el.getAttribute(a);
          if (!/[؀-ۿ]/.test(val)) return;
          el.setAttribute(key, val);
        }
        const o = el.getAttribute(key);
        const v = lang === "en" ? tr(o) : null;
        el.setAttribute(a, v === null ? o : v);
      });
    });
  }

  function setLang(l, silent) {
    lang = l === "en" ? "en" : "ar";
    const h = document.documentElement;
    h.lang = lang; h.dir = lang === "en" ? "ltr" : "rtl";
    if (document.body) { document.body.dir = h.dir; document.body.lang = lang; }
    try { localStorage.setItem("lang", lang); } catch (e) {}
    // العنوان
    document.title = lang === "en" ? EN["بطولة أساسيات البارا تايكوندو 2026"] : "بطولة أساسيات البارا تايكوندو 2026";
    apply(document.documentElement);
    if (!silent) document.dispatchEvent(new CustomEvent("langchange", { detail: lang }));
  }

  window.I18N = { t, apply, setLang, get lang() { return lang; }, EN };
